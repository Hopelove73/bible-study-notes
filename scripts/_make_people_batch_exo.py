def main():
    people = load()
    for cid, cards in BATCH.items():
        batch = [resident(people, "yahweh", cid), resident(people, "isaiah", cid)] + cards
        path = os.path.join(ROOT, "logs", "people_%s.json" % cid.replace("-", ""))
        io.open(path, "w", encoding="utf-8", newline="\n").write(
            json.dumps(batch, ensure_ascii=False, indent=2))
        print("wrote %s (%d)" % (path, len(batch)))


if __name__ == "__main__":
    main()
