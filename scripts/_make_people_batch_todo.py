def load():
    raw = io.open(PEOPLE, encoding="utf-8").read()
    i, j = raw.find("["), raw.rfind("]")
    return json.loads(raw[i:j + 1])


def resident(people, rid, cid):
    for p in people:
        if p["id"] == rid:
            q = dict(p)
            q["chapters"] = sorted(set(q.get("chapters", [])) | {cid})
            return q
    raise SystemExit("找不到常驻卡 %s" % rid)


